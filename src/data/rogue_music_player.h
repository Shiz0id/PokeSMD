// The music player's curated tracklist.
//
// THIS IS A TABLE. Adding a track is a row here; it must never become an edit to
// rogue_music_player.c. The player derives everything it shows from these rows
// and from the song table -- there is no second list anywhere.
//
// Each row is { songId, gbsId, playlist, name }:
//
//   songId   the ordinary m4a track, always played when GB Sounds is off.
//
//   gbsId    an EXPLICIT Game Boy arrangement, or GBS_MUSIC_NONE to fall through
//            to the third column of sound/song_table.inc.
//
//            Both paths exist because there are two kinds of GB arrangement in
//            this ROM and only one of them is wired into field music. A real GBS
//            transcription (mus_petalburg_woods, and the RSE and GSC/RBY sets)
//            lives in that third column, GetSong finds it, and the field music
//            plays it when the flag is on -- those rows leave gbsId as NONE so
//            there is exactly one source of truth for them.
//
//            The thirty-six *_PSG entries are the other kind: the original
//            Emerald song rebuilt against a PSG-only voicegroup, sequenced by
//            m4a, not GBS data at all. Commit 2f9616684e deliberately unwired
//            them from the third column after they had been shipped as "GBS"
//            -- they are kept, and reachable ONLY from this table, so the music
//            player can still play them.
//
//   playlist which menu they appear under. Rows of one playlist need not be
//            contiguous; the player filters.
//
//   name     what the player shows. Hand-written, not derived from the MUS_
//            identifier, because the identifier is frequently not the track's
//            name: MUS_DESERT's label is mus_route111, MUS_ROUTE119 is also
//            every water route, and the RG_SEVII_* ids are Johto music.
//
// A wrong gbsId is a SILENT failure of exactly the kind this repo keeps
// producing -- the track plays, it is simply the wrong arrangement, and nothing
// fails to build. tools/rogue/check_music_player_table.py resolves every row
// against sound/song_table.inc and src/gbs_song_table.c and is what catches it.

