#define ROGUE_MUSIC_TRACK_COUNT ARRAY_COUNT(sRogueMusicTracks)

// The most rows any ONE list in the player can hold, which is what its
// ListMenuItem array is sized by -- NOT the tracklist length.
//
// The player never shows every track at once. A list is either the top-level
// playlists, one playlist's sublists, or the tracks of a SINGLE playlist, so the
// bound is the larger of RMP_PLAYLIST_COUNT and the biggest playlist (PSG
// REMIXES, 35). Sizing the array by ROGUE_MUSIC_TRACK_COUNT instead made the
// player's one allocation 2 KB and, worse, made it grow by 8 bytes for every
// track imported -- a heap cost that rises with the tracklist forever while the
// thing it pays for never gets any bigger.
//
// tools/rogue/check_music_player_table.py asserts both bounds fit. Raise this
// when it says to; it is deliberately not derived, because a derived value would
// silently absorb a playlist that had grown past what the menu can sensibly show.
#define ROGUE_MUSIC_MAX_LIST_ROWS 48

