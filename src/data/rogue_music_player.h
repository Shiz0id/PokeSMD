// Playlists can nest one level: a playlist whose parent is set appears inside
// that parent instead of at the top. RMP_PLAYLIST_PSG sits under GAME BOY
// because the remixes belong beside the real Game Boy material without being
// confused for it.
//
// EVERY PLAYLIST MUST BE LISTED HERE, top level ones included. The sentinel is
// 0xFF but a designated initialiser zero-fills what it omits, and 0 is
// RMP_PLAYLIST_DUNGEON -- so a playlist left out of this table does not default
// to the top level, it silently becomes a child of DUNGEON FLOORS. That is
// exactly what happened to the nine imported playlists below: they built clean,
// passed every check, and simply were not where they should have been.
// check_music_player_table.py now requires an explicit row for each.
